import { open, shot } from './lib.mjs';
const lang = process.argv[2] || 'en', device = process.argv[3] || 'ipad-land';
const { page, browser, errors } = await open({ lang, device });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const w = (ms) => page.waitForTimeout(ms);
await page.evaluate(async () => { const st = await import('./js/core/store.js'); st.S.settings.dailyLimit = 0; st.S.settings.bedtime = ''; st.S.unlocked.snack = true; st.S.stands.snack = { tickets: 1, bank: 50000, up: { candy: 1, cones: 1, slush: 1, cooler: 1, grill: 1, fryer: 1, field2: 1, field3: 1, field4: 1 }, season: { no: 6, day: 0 }, seasons: 6 }; });
const stateKeys = await page.evaluate(() => JSON.stringify(window.__lab.S.stands.snack));
await page.evaluate(() => { location.hash = '#/stands/snack'; }); await w(800);
ok(!!(await page.$('.forecast')), 'snack plan screen opens');
await shot(page, `snack-plan2-${lang}-${device}`);
const shopTxt = await page.evaluate(() => document.body.innerText);
console.log('  stand state keys:', stateKeys.slice(0, 120));
console.log('  mentions candy/slush/cone/field:', ['andy', 'lush', 'one', 'ield', 'ampo', 'ulce', 'ranizado', 'ono'].filter((k) => shopTxt.includes(k)).join(','));
const rows = await page.$$('.mrow'); console.log('  menu rows:', rows.length);
ok(rows.length >= 11, 'all 11 menu items (incl. candy, cone, slush, frozen lemonade) listed: ' + rows.length);
await page.locator('.mrow .mplus, .mrow button').nth(1).click().catch(() => {});
const stockMax = await page.evaluate(async () => { const m = await import('./js/stands/sims.js'); return { max: m.SNACK.stockMax(window.__lab.S.stands.snack.up), step: m.SNACK.stockStep(window.__lab.S.stands.snack.up), serve: m.SNACK.serveCap(window.__lab.S.stands.snack.up) }; });
console.log('  with 3 extra fields:', JSON.stringify(stockMax));
ok(stockMax.max >= 40 + 40 + 80 + 160, 'stock limit grows with fields (' + stockMax.max + ')');
await page.locator('.openrow .btn.go').click(); await w(400);
await page.locator('button', { hasText: /Skip to the end|Saltar al final/ }).click(); await w(600);
ok(!!(await page.$('.receipt, .rcpt, .recap')) || (await page.evaluate(() => document.body.innerText)).match(/profit|ganancia/i), 'a big-crowd day finishes and shows a receipt');
await shot(page, `snack-bigday-${lang}-${device}`);
ok(errors.length === 0, 'console clean ' + errors.join('/'));
await browser.close(); process.exit(fails ? 1 : 0);
